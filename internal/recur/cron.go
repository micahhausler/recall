package recur

import (
	"fmt"
	"io"
	"os/exec"
	"strings"

	"github.com/micahhausler/recall/internal/config"
)

func init() {
	Register("cron", func(s Setup) Scheduler { return &cron{s} })
}

// cron owns one marked block at the end of the user's crontab; lines outside
// it are untouched. The `crontab` command comes from PATH, so tests install
// a fake.
type cron struct {
	Setup
}

func (c *cron) begin() string {
	return fmt.Sprintf("# BEGIN recall-recur %s (generated by recall; edit [recur.jobs] in your recall config, then run recall recur sync)", c.Prefix)
}

func (c *cron) end() string {
	return fmt.Sprintf("# END recall-recur %s", c.Prefix)
}

// line renders one job. cron ends the command at an unescaped % and feeds
// the rest to stdin, so % is escaped.
func (c *cron) line(j config.Job) string {
	args := make([]string, 0, 6)
	for _, a := range c.runArgs(j.Name) {
		args = append(args, shQuote(a))
	}
	cmd := strings.Join(args, " ")
	if c.ConfigEnv != "" {
		cmd = fmt.Sprintf("RECALL_CONFIG=%s %s", shQuote(c.ConfigEnv), cmd)
	}
	return strings.ReplaceAll(j.Schedule+" "+cmd, "%", `\%`)
}

func (c *cron) Sync(jobs map[string]config.Job, check bool, out io.Writer) ([]Action, error) {
	read := exec.Command("crontab", "-l")
	current := ""
	if data, err := read.Output(); err == nil {
		current = string(data)
	}

	// Drop our old block wherever it is; keep everything else verbatim.
	var kept, old []string
	inside := false
	beginBare := strings.SplitN(c.begin(), " (", 2)[0]
	for _, line := range strings.Split(strings.TrimSuffix(current, "\n"), "\n") {
		switch {
		case line == beginBare || strings.HasPrefix(line, beginBare+" "):
			inside = true
		case line == c.end():
			inside = false
		case inside:
			old = append(old, line)
		default:
			kept = append(kept, line)
		}
	}
	if current == "" {
		kept = nil
	}
	if inside {
		return nil, fmt.Errorf("crontab has a recall-recur BEGIN marker without END; fix it by hand (crontab -e)")
	}

	if len(old) == 0 && len(jobs) == 0 {
		return nil, nil
	}
	if check {
		fmt.Fprintf(out, "crontab: %d lines in the recall-recur %s block\n", len(old), c.Prefix)
	}
	var block []string
	for _, j := range sortedJobs(jobs) {
		block = append(block, c.line(j))
	}
	if c.CronTZ != "" && len(block) > 0 {
		block = append([]string{"CRON_TZ=" + c.CronTZ}, block...)
	}
	for len(kept) > 0 && strings.TrimSpace(kept[len(kept)-1]) == "" {
		kept = kept[:len(kept)-1]
	}
	// The block goes last so nothing in it affects lines you wrote.
	newLines := append([]string{}, kept...)
	if len(kept) > 0 && len(block) > 0 {
		newLines = append(newLines, "")
	}
	if len(block) > 0 {
		newLines = append(append(append(newLines, c.begin()), block...), c.end())
	}
	updated := ""
	if len(newLines) > 0 {
		updated = strings.Join(newLines, "\n") + "\n"
	}
	if check {
		inOld := map[string]bool{}
		for _, line := range old {
			inOld[line] = true
		}
		for _, line := range block {
			if inOld[line] {
				fmt.Fprintf(out, "ok     %s\n", line)
			}
		}
	}
	if updated == current || (strings.TrimSpace(updated) == "" && strings.TrimSpace(current) == "") {
		return nil, nil
	}

	var plan []Action
	inOld, inBlock := map[string]bool{}, map[string]bool{}
	for _, l := range old {
		inOld[l] = true
	}
	for _, l := range block {
		inBlock[l] = true
	}
	for _, l := range block {
		if !inOld[l] {
			plan = append(plan, Action{"add", l})
		}
	}
	for _, l := range old {
		if !inBlock[l] {
			plan = append(plan, Action{"remove", l})
		}
	}
	if len(plan) == 0 {
		plan = append(plan, Action{"rewrite", "crontab layout (the block moves back to the end)"})
	}
	for _, a := range plan {
		fmt.Fprintf(out, "%-6s %s\n", a.Op, a.What)
	}
	if !check {
		write := exec.Command("crontab", "-")
		write.Stdin = strings.NewReader(updated)
		if msg, err := write.CombinedOutput(); err != nil {
			return nil, fmt.Errorf("crontab: %s", strings.TrimSpace(string(msg)))
		}
	}
	return plan, nil
}

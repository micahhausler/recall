func TestRunJob(t *testing.T) {
	home := t.TempDir()
	s := testSetup(home)
	s.Env = map[string]string{"GREETING": "hi $HOME", "CRON_TZ": "UTC"}
	j := map[string]config.Job{"j": {Name: "j", Command: `echo "$GREETING:${CRON_TZ-unset}:$PWD"; exit 3`}}
	rc, err := s.Run("j", j, nil)
	if err != nil || rc != 3 {
		t.Fatalf("rc = %d, %v; want 3", rc, err)
	}
	data, err := os.ReadFile(filepath.Join(StateDir(home), "j.log"))
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimSuffix(string(data), "\n"), "\n")
	if !strings.Contains(lines[0], "start j: ") {
		t.Errorf("line 0 = %q", lines[0])
	}
	parts := strings.SplitN(lines[1], ":", 3)
	if parts[0] != "hi "+home || parts[1] != "unset" {
		t.Errorf("env line = %q; want $HOME expanded and CRON_TZ unexported", lines[1])
	}
	if real, _ := filepath.EvalSymlinks(parts[2]); real != mustEval(t, home) {
		t.Errorf("cwd = %q, want home", parts[2])
	}
	if !strings.Contains(lines[2], "exit 3") {
		t.Errorf("line 2 = %q", lines[2])
	}

	if rc, err := s.Run("nope", j, nil); err == nil || rc != 2 {
		t.Errorf("unknown job: rc=%d err=%v", rc, err)
	}
}

func mustEval(t *testing.T, p string) string {
	t.Helper()
	out, err := filepath.EvalSymlinks(p)
	if err != nil {
		t.Fatal(err)
	}
	return out
}


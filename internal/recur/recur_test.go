// fakeLaunchctl tracks loaded labels in a directory.
func fakeLaunchctl(t *testing.T, failBootstrap bool) string {
	t.Helper()
	dir := t.TempDir()
	os.MkdirAll(filepath.Join(dir, "loaded"), 0o755)
	script := `#!/bin/sh
D="$(dirname "$0")/loaded"
label() { b="${1##*/}"; echo "${b%.plist}"; }
case "$1" in
print) [ -e "$D/$(label "$2")" ] || exit 113 ;;
bootout) L="$(label "$2")"; [ -e "$D/$L" ] || exit 3; rm -f "$D/$L" ;;
bootstrap) ` + map[bool]string{true: `echo "Input/output error" >&2; exit 5`, false: `touch "$D/$(label "$3")"`}[failBootstrap] + ` ;;
esac
`
	fakeBin(t, dir, "launchctl", script)
	t.Setenv("PATH", dir+string(os.PathListSeparator)+os.Getenv("PATH"))
	return filepath.Join(dir, "loaded")
}

func loadedLabels(t *testing.T, dir string) []string {
	t.Helper()
	entries, _ := os.ReadDir(dir)
	var out []string
	for _, e := range entries {
		out = append(out, e.Name())
	}
	return out
}


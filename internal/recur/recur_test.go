func jobs(names ...string) map[string]config.Job {
	m := map[string]config.Job{}
	for _, n := range names {
		m[n] = config.Job{Name: n, Schedule: "0 12 * * 1", Command: "x"}
	}
	return m
}

func syncCron(t *testing.T, s Setup, j map[string]config.Job, check bool) ([]Action, string) {
	t.Helper()
	var out strings.Builder
	plan, err := (&cron{s}).Sync(j, check, &out)
	if err != nil {
		t.Fatal(err)
	}
	return plan, out.String()
}

func ops(plan []Action) []string {
	var out []string
	for _, a := range plan {
		out = append(out, a.Op)
	}
	return out
}

func TestCronAddsBlockAndIsIdempotent(t *testing.T) {
	read := fakeCrontab(t, userTab)
	s := testSetup(t.TempDir())
	s.CronTZ = "UTC"
	plan, _ := syncCron(t, s, jobs("a", "b"), false)
	if !reflect.DeepEqual(ops(plan), []string{"add", "add", "add"}) {
		t.Fatalf("plan = %v", plan)
	}
	got, _ := read()
	if !strings.HasPrefix(got, userTab) {
		t.Fatalf("user lines disturbed:\n%s", got)
	}
	block := strings.Split(got[len(userTab):], "\n")
	want := []string{
		"",
		"# BEGIN recall-recur test.prefix (generated by recall; edit [recur.jobs] in your recall config, then run recall recur sync)",
		"CRON_TZ=UTC",
		"0 12 * * 1 RECALL_CONFIG=/cfg/config.toml /x/bin/recall recur run a",
		"0 12 * * 1 RECALL_CONFIG=/cfg/config.toml /x/bin/recall recur run b",
		"# END recall-recur test.prefix",
		"",
	}
	if !reflect.DeepEqual(block, want) {
		t.Fatalf("block = %q, want %q", block, want)
	}
	plan, _ = syncCron(t, s, jobs("a", "b"), false)
	if len(plan) != 0 {
		t.Errorf("second sync plan = %v, want none", plan)
	}
	now, _ := read()
	if now != got {
		t.Error("second sync changed the crontab")
	}
}


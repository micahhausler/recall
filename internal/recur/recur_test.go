func TestCronBlockMovedBackToEnd(t *testing.T) {
	read, tab := fakeCrontabAt(t, userTab)
	s := testSetup(t.TempDir())
	syncCron(t, s, jobs("a"), false)
	got, _ := read()
	os.WriteFile(tab, []byte(got+"5 5 * * * echo later\n"), 0o644)
	plan, _ := syncCron(t, s, jobs("a"), true)
	if !reflect.DeepEqual(ops(plan), []string{"rewrite"}) {
		t.Errorf("check plan = %v, want a rewrite", plan)
	}
	syncCron(t, s, jobs("a"), false)
	lines := strings.Split(strings.TrimSuffix(mustRead(t, read), "\n"), "\n")
	if lines[len(lines)-1] != "# END recall-recur test.prefix" {
		t.Errorf("last line = %q, want the END marker", lines[len(lines)-1])
	}
	if !strings.Contains(mustRead(t, read), "5 5 * * * echo later") {
		t.Error("the user's later line was lost")
	}
}

func mustRead(t *testing.T, read func() (string, bool)) string {
	t.Helper()
	got, ok := read()
	if !ok {
		t.Fatal("no crontab")
	}
	return got
}


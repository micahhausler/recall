func TestLaunchdLifecycle(t *testing.T) {
	loaded := fakeLaunchctl(t, false)
	home := t.TempDir()
	s := testSetup(home)
	plan, _ := syncLaunchd(t, s, jobs("a"), false)
	if !reflect.DeepEqual(plan, []Action{{"add", "test.prefix.a"}}) {
		t.Fatalf("plan = %v", plan)
	}
	path := filepath.Join(AgentsDir(home), "test.prefix.a.plist")
	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	for _, want := range []string{
		"<string>/x/bin/recall</string>", "<string>recur</string>", "<string>run</string>", "<string>a</string>",
		"<key>Weekday</key>", "<integer>1</integer>",
		"<key>RECALL_CONFIG</key>", "<string>/cfg/config.toml</string>",
	} {
		if !strings.Contains(string(data), want) {
			t.Errorf("plist misses %s", want)
		}
	}
	if got := loadedLabels(t, loaded); !reflect.DeepEqual(got, []string{"test.prefix.a"}) {
		t.Fatalf("loaded = %v", got)
	}

	if plan, _ := syncLaunchd(t, s, jobs("a"), false); len(plan) != 0 {
		t.Errorf("second sync plan = %v", plan)
	}

	os.Remove(filepath.Join(loaded, "test.prefix.a")) // booted out by hand
	plan, _ = syncLaunchd(t, s, jobs("a"), false)
	if !reflect.DeepEqual(plan, []Action{{"load", "test.prefix.a"}}) {
		t.Errorf("plan = %v, want a load", plan)
	}

	j := jobs("a")
	a := j["a"]
	a.Schedule = "0 13 * * 1"
	j["a"] = a
	plan, _ = syncLaunchd(t, s, j, false)
	if !reflect.DeepEqual(plan, []Action{{"update", "test.prefix.a"}}) {
		t.Errorf("plan = %v, want an update", plan)
	}
	data, _ = os.ReadFile(path)
	if !strings.Contains(string(data), "<integer>13</integer>") {
		t.Error("updated plist misses hour 13")
	}

	plan, _ = syncLaunchd(t, s, nil, false)
	if !reflect.DeepEqual(plan, []Action{{"remove", "test.prefix.a"}}) {
		t.Errorf("plan = %v, want a remove", plan)
	}
	if _, err := os.Stat(path); !os.IsNotExist(err) {
		t.Error("plist still on disk after remove")
	}
	if got := loadedLabels(t, loaded); len(got) != 0 {
		t.Errorf("still loaded: %v", got)
	}
}

